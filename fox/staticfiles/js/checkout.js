// Open the edit address form (make it visible)
function openEditForm(formId) {
    var form = document.getElementById(formId);
    form.style.display = 'block'; // Show the edit form
}

// Close the edit address form (hide it)
function closeEditForm(formId) {
    var form = document.getElementById(formId);
    form.style.display = 'none'; // Hide the edit form
}
